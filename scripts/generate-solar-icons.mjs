import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..");

const jsonPath = path.join(rootDir, "node_modules", "@iconify-json", "solar", "icons.json");
const infoPath = path.join(rootDir, "node_modules", "@iconify-json", "solar", "info.json");
const outputDir = path.join(rootDir, "src", "components", "icons", "solar");
const outputFile = path.join(outputDir, "index.tsx");

if (!fs.existsSync(jsonPath)) {
  console.error(`Erro: Arquivo não encontrado: ${jsonPath}. Execute 'npm install -D @iconify-json/solar'.`);
  process.exit(1);
}

const iconsData = JSON.parse(fs.readFileSync(jsonPath, "utf-8"));
const infoData = fs.existsSync(infoPath) ? JSON.parse(fs.readFileSync(infoPath, "utf-8")) : {};

// Mapeamento dos 17 ícones Solar Bold Duotone
const ICON_MAPPING = [
  { id: "speedometer-middle-bold-duotone", componentName: "SolarSpeedometerMiddleIcon", alias: "SolarDashboardIcon", label: "Dashboard" },
  { id: "bot-bold-duotone", componentName: "SolarBotIcon", alias: "SolarBotsIcon", label: "Bots" },
  { id: "cart-large-2-bold-duotone", componentName: "SolarCartLarge2Icon", alias: "SolarCartIcon", label: "Pedidos" },
  { id: "user-id-bold-duotone", componentName: "SolarUserIdIcon", alias: "SolarCustomersIcon", label: "Clientes" },
  { id: "users-group-rounded-bold-duotone", componentName: "SolarUsersGroupRoundedIcon", alias: "SolarSellersIcon", label: "Vendedores e Taxas" },
  { id: "hand-money-bold-duotone", componentName: "SolarHandMoneyIcon", alias: "SolarCommissionIcon", label: "Comissão da Plataforma" },
  { id: "chart-2-bold-duotone", componentName: "SolarChart2Icon", alias: "SolarReportsIcon", label: "Relatórios" },
  { id: "box-bold-duotone", componentName: "SolarBoxIcon", alias: "SolarPlansIcon", label: "Planos WebGran" },
  { id: "card-2-bold-duotone", componentName: "SolarCard2Icon", alias: "SolarSubscriptionsIcon", label: "Assinaturas WebGran" },
  { id: "tuning-4-bold-duotone", componentName: "SolarTuning4Icon", alias: "SolarFeaturesIcon", label: "Recursos & Features" },
  { id: "wallet-money-bold-duotone", componentName: "SolarWalletMoneyIcon", alias: "SolarGatewaysIcon", label: "Gateways dos Vendedores" },
  { id: "video-library-bold-duotone", componentName: "SolarVideoLibraryIcon", alias: "SolarVideoLibraryMenuIcon", label: "Biblioteca de Vídeos" },
  { id: "clapperboard-play-bold-duotone", componentName: "SolarClapperboardPlayIcon", alias: "SolarVideoOverviewIcon", label: "Visão Geral (Vídeos)" },
  { id: "cloud-storage-bold-duotone", componentName: "SolarCloudStorageIcon", alias: "SolarStoragePlansIcon", label: "Planos de Armazenamento" },
  { id: "palette-round-bold-duotone", componentName: "SolarPaletteRoundIcon", alias: "SolarThemesIcon", label: "Temas" },
  { id: "settings-bold-duotone", componentName: "SolarSettingsIcon", alias: "SolarSettingsMenuIcon", label: "Configurações" },
  { id: "shop-2-bold-duotone", componentName: "SolarShop2Icon", alias: "SolarSellerPanelIcon", label: "Painel do Vendedor" },
];

// Validação estrita: se algum identificador não existir, falhar imediatamente
const missingIcons = [];
for (const item of ICON_MAPPING) {
  const iconExists = iconsData.icons && (iconsData.icons[item.id] || (iconsData.aliases && iconsData.aliases[item.id]));
  if (!iconExists) {
    missingIcons.push(item.id);
  }
}

if (missingIcons.length > 0) {
  console.error("ERRO: Os seguintes identificadores não existem na coleção Solar:");
  for (const m of missingIcons) {
    console.error(`  - ${m}`);
  }
  process.exit(1);
}

const figmaUrl = infoData.author?.url || "https://www.figma.com/community/file/1166831539721848736";
const licenseTitle = infoData.license?.title || "CC BY 4.0";
const authorName = infoData.author?.name || "480 Design";

let code = `/**
 * Solar Icon Set by ${authorName}, ${licenseTitle}
 * Source: ${figmaUrl}
 * Auto-generated by scripts/generate-solar-icons.mjs
 * Total extracted icons: ${ICON_MAPPING.length}
 */

import React from "react";

export interface SolarIconProps extends React.SVGProps<SVGSVGElement> {
  size?: number;
  className?: string;
}

`;

for (const item of ICON_MAPPING) {
  const iconObj = iconsData.icons[item.id] || (iconsData.aliases && iconsData.aliases[item.id]);
  const width = iconObj.width || iconsData.width || 24;
  const height = iconObj.height || iconsData.height || 24;

  // Converter atributos para React JSX
  const jsxBody = iconObj.body
    .replace(/fill-rule=/g, "fillRule=")
    .replace(/clip-rule=/g, "clipRule=");

  code += `/**
 * ${item.label} (${item.id})
 */
export function ${item.componentName}({
  size = 16,
  className,
  ...props
}: SolarIconProps) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 ${width} ${height}"
      fill="currentColor"
      aria-hidden="true"
      focusable="false"
      className={className}
      {...props}
    >
      ${jsxBody}
    </svg>
  );
}

export const ${item.alias} = ${item.componentName};

`;
}

// Exportar dicionário com metadados para uso na página de preview
code += `export const SOLAR_MENU_ICONS = [
${ICON_MAPPING.map(
  (item) => `  {
    id: "${item.id}",
    name: "${item.componentName}",
    alias: "${item.alias}",
    label: "${item.label}",
    Component: ${item.componentName},
  },`
).join("\n")}
] as const;
`;

if (!fs.existsSync(outputDir)) {
  fs.mkdirSync(outputDir, { recursive: true });
}

fs.writeFileSync(outputFile, code, "utf-8");
console.log(`Sucesso: ${ICON_MAPPING.length} ícones Solar Bold Duotone gerados em ${outputFile}`);

